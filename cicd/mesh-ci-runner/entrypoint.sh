#!/bin/bash
set -e

# Validate MESH_NODE_NAME to prevent sed injection via special characters.
NODE_NAME="${MESH_NODE_NAME:-ci-runner}"
if [[ "${NODE_NAME}" =~ [^a-zA-Z0-9_-] ]]; then
  echo "ERROR: MESH_NODE_NAME contains invalid characters: ${NODE_NAME}" >&2
  exit 1
fi

git config --global http.https://localhost:7979.sslVerify false

if [ ! -f ~/.mesh/mesh.toml ]; then
  mesh init
  sed -i "s/^name = .*/name = \"${NODE_NAME}\"/" ~/.mesh/mesh.toml
fi

# Configure buildkitd address for uses: image jobs.
# BUILDKIT_HOST is set by the deployment to the standalone buildkitd Service DNS name.
BUILDKIT_ENDPOINT="${BUILDKIT_HOST:-tcp://buildkitd.ci.svc.cluster.local:1234}"
if grep -q '^buildkit_addr' ~/.mesh/mesh.toml; then
  sed -i "s|^buildkit_addr = .*|buildkit_addr = \"${BUILDKIT_ENDPOINT}\"|" ~/.mesh/mesh.toml
else
  sed -i "/^\[runner\]/a buildkit_addr = \"${BUILDKIT_ENDPOINT}\"" ~/.mesh/mesh.toml
fi

# Configure registry URL for uses: image jobs.
# REGISTRY_URL is set by the deployment; defaults to the in-cluster registry.
REGISTRY="${REGISTRY_URL:-registry.mesh-system.svc.cluster.local:5000}"
if grep -q '^registry_url' ~/.mesh/mesh.toml; then
  sed -i "s|^registry_url = .*|registry_url = \"${REGISTRY}\"|" ~/.mesh/mesh.toml
else
  sed -i "/^\[runner\]/a registry_url = \"${REGISTRY}\"" ~/.mesh/mesh.toml
fi

# Configure docker buildx to use the standalone buildkitd pod as the remote builder.
# Certs are generated by the buildkitd-cert-gen Job and mounted from the
# buildkitd-certs Secret at /certs (client-side: ca.pem, client.pem, client-key.pem).
BUILDX_DIR="${HOME}/.docker/buildx"
mkdir -p "${BUILDX_DIR}/instances"

# Wait up to 30s for buildkitd to be reachable (TCP connect check).
echo "Waiting for buildkitd at ${BUILDKIT_ENDPOINT}..."
BUILDKITD_READY=0
for i in $(seq 1 30); do
  HOST=$(echo "${BUILDKIT_ENDPOINT}" | sed 's|tcp://||')
  ADDR="${HOST%%:*}"
  PORT="${HOST##*:}"
  if (echo > /dev/tcp/"${ADDR}"/"${PORT}") 2>/dev/null; then
    echo "buildkitd is ready"
    BUILDKITD_READY=1
    break
  fi
  echo "  attempt $i/30 — retrying in 1s"
  sleep 1
done

if [ "${BUILDKITD_READY}" -eq 0 ]; then
  echo "WARNING: buildkitd did not become ready in 30s — proceeding anyway"
fi

# Write the builder config directly (avoids needing a Docker daemon for 'docker buildx create').
cat > "${BUILDX_DIR}/instances/ci-builder" <<EOF
{
  "Name": "ci-builder",
  "Driver": "remote",
  "Nodes": [
    {
      "Name": "ci-builder0",
      "Endpoint": "${BUILDKIT_ENDPOINT}",
      "Platforms": null,
      "DriverOpts": {
        "cacert": "/certs/ca.pem",
        "cert": "/certs/client.pem",
        "key": "/certs/client-key.pem"
      },
      "Flags": []
    }
  ],
  "Dynamic": false
}
EOF
# Set ci-builder as the current builder (same format Docker stores it).
echo "ci-builder" > "${BUILDX_DIR}/current"
echo "buildx ci-builder configured (endpoint: ${BUILDKIT_ENDPOINT})"

exec mesh start
